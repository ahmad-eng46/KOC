    '00000004-0000-0000-0000-000000000011','00000004-0000-0000-0000-000000000012',
    '00000004-0000-0000-0000-000000000013','00000004-0000-0000-0000-000000000014',
    '00000004-0000-0000-0000-000000000015','00000004-0000-0000-0000-000000000016',
    '00000004-0000-0000-0000-000000000017','00000004-0000-0000-0000-000000000018',
    '00000004-0000-0000-0000-000000000019','00000004-0000-0000-0000-000000000020'
  ];

  -- Product pool: first 6 (bulk fuel products)
  prods UUID[] := ARRAY[
    '00000005-0000-0000-0000-000000000001','00000005-0000-0000-0000-000000000002',
    '00000005-0000-0000-0000-000000000003','00000005-0000-0000-0000-000000000004',
    '00000005-0000-0000-0000-000000000005','00000005-0000-0000-0000-000000000006'
  ];

  prices BIGINT[] := ARRAY[28500, 30200, 26800, 24500, 22000, 19500];
  pp     BIGINT[] := ARRAY[27800, 29400, 26000, 23700, 21200, 18800];

  i         INTEGER;
  inv_id    UUID;
  inv_num   TEXT;
  cust_id   UUID;
  inv_date  DATE;
  p_idx     INTEGER;
  qty1      NUMERIC;
  qty2      NUMERIC;
  line1     BIGINT;
  line2     BIGINT;
  subtotal  BIGINT;
  discount  BIGINT;
  total     BIGINT;
BEGIN
  FOR i IN 1..100 LOOP
    inv_id   := gen_random_uuid();
    inv_num  := 'INV-' || LPAD(i::TEXT, 4, '0');
    cust_id  := custs[1 + mod(i - 1, 20)];
    inv_date := CURRENT_DATE - (mod(i * 7, 90))::INTEGER;
    p_idx    := 1 + mod(i - 1, 6);

    qty1     := (100 + mod(i * 13, 900))::NUMERIC;
    qty2     := (50  + mod(i * 17, 450))::NUMERIC;
    line1    := (qty1 * prices[p_idx])::BIGINT;
    line2    := (qty2 * prices[1 + mod(p_idx, 6)])::BIGINT;
    subtotal := line1 + line2;
    discount := CASE WHEN mod(i, 5) = 0 THEN (subtotal / 100) ELSE 0 END;
    total    := subtotal - discount;

    -- Invoice header
    INSERT INTO public.invoices
      (id, business_id, customer_id, invoice_number, status, issue_date,
       subtotal_paisa, discount_paisa, total_paisa, paid_paisa, created_by)
    VALUES
      (inv_id, biz, cust_id, inv_num, 'issued', inv_date,
       subtotal, discount, total, 0, admin_id);

    -- Line item 1
    INSERT INTO public.invoice_items
      (invoice_id, product_id, quantity, unit_price_paisa,
       purchase_price_at_sale_paisa, line_total_paisa)
    VALUES
      (inv_id, prods[p_idx], qty1, prices[p_idx], pp[p_idx], line1);

    -- Line item 2
    INSERT INTO public.invoice_items
      (invoice_id, product_id, quantity, unit_price_paisa,
       purchase_price_at_sale_paisa, line_total_paisa)
    VALUES
      (inv_id, prods[1 + mod(p_idx, 6)], qty2, prices[1 + mod(p_idx, 6)],
       pp[1 + mod(p_idx, 6)], line2);

    -- Stock out
    INSERT INTO public.stock_movements (business_id, product_id, invoice_id, type, quantity)
    VALUES (biz, prods[p_idx], inv_id, 'out', qty1);

    INSERT INTO public.stock_movements (business_id, product_id, invoice_id, type, quantity)
    VALUES (biz, prods[1 + mod(p_idx, 6)], inv_id, 'out', qty2);

  END LOOP;
END;
$$;

