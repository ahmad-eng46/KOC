-- 100 Invoices spread across last 90 days
-- Using a DO block so we can compute totals correctly.
-- Each invoice has 1–3 line items; totals are exact sums.
-- ─────────────────────────────────────────────
DO $$
DECLARE
  biz  UUID := '00000002-0000-0000-0000-000000000001';
  admin_id UUID := '00000001-0000-0000-0000-000000000001';

  -- Customer pool (first 20 for variety)
  custs UUID[] := ARRAY[
    '00000004-0000-0000-0000-000000000001','00000004-0000-0000-0000-000000000002',
    '00000004-0000-0000-0000-000000000003','00000004-0000-0000-0000-000000000004',
    '00000004-0000-0000-0000-000000000005','00000004-0000-0000-0000-000000000006',
    '00000004-0000-0000-0000-000000000007','00000004-0000-0000-0000-000000000008',
